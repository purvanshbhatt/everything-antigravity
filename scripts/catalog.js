#!/usr/bin/env node
'use strict';
/**
 * Generates the eag-* index skills and docs/CATALOG.md from the skills, agents and rules on disk.
 * Run: npm run catalog
 *
 * Why index skills: Antigravity gives every plugin's model-visible skills one shared
 * 20,000-token budget and drops the most expensive skills first when it overflows. Most EAG
 * skills are therefore slash-only (`disable-model-invocation: true`) and cost nothing until used;
 * the model finds them through one small eag-* index skill per category.
 */
const fs = require('node:fs');
const path = require('node:path');
const { validateRepo } = require('./lib/validate');

const ROOT = path.resolve(__dirname, '..');
const CATEGORIES = require('./categories.json');
const WORKFLOWS_KEY = '_workflows';
const MARKER = '<!-- Generated by scripts/catalog.js from scripts/categories.json. Do not edit by hand; run `npm run catalog`. -->';

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (s) => esc(String(s).split(/(?<=\.)\s/)[0]);
// Index rows stay compact so every index file stays well under the 16 KB skill guideline.
const clip = (s, max = 150) => {
  const t = short(s);
  return t.length <= max ? t : `${t.slice(0, t.lastIndexOf(' ', max - 1))}…`;
};
const title = (key) => (key === WORKFLOWS_KEY ? 'Workflows' : key);

/** @returns {Array<{key: string, slug: string, description: string, covers: string, items: object[]}>} */
function groups(r) {
  const real = r.skills.filter((s) => !s.index);
  const workflows = real.filter((s) => s.workflow);
  const knowledge = real.filter((s) => !s.workflow);
  return Object.entries(CATEGORIES).map(([key, c]) => ({
    key,
    slug: c.slug,
    description: c.description,
    covers: c.covers,
    items: key === WORKFLOWS_KEY ? workflows : knowledge.filter((s) => c.skills.includes(s.name)),
  }));
}

function indexSkill(g) {
  const n = g.items.length;
  const isWorkflows = g.key === WORKFLOWS_KEY;
  const lines = [
    '---',
    `name: ${g.slug}`,
    'description: >-',
    `  ${g.description.replace('{n}', String(n))}`,
    '---',
    '',
    MARKER,
    '',
    `# ${title(g.key)}: ${n} ${isWorkflows ? 'workflows' : 'playbooks'}`,
    '',
    `Covers ${g.covers}.`,
    '',
    'These skills are not preloaded, so they cost no context until one is needed. This index is how you find them.',
    '',
    '## How to use this index',
    '',
    '1. Find the row that best matches the task. Match on the technology, the artifact being produced and the job to be done, not on a single keyword.',
    '2. Open the linked `SKILL.md` with your file viewer before you act. Paths are relative to this file.',
    '3. Follow that skill as written: its workflow, its Check steps and its verification checklist. Read its `references/` files only when the skill points you to them.',
    '4. If two rows apply, read both and follow the more specific one where they differ. If none applies, say so and continue with general knowledge.',
    `5. The user can also run any row directly as a slash command, for example \`/${g.items[0] ? g.items[0].name : 'feature-dev'}\`.`,
    '',
    `## ${isWorkflows ? 'Workflows' : 'Playbooks'}`,
    '',
    `| ${isWorkflows ? 'Command' : 'Skill'} | Use it for |`,
    '| :--- | :--- |',
    ...g.items.map((s) => `| [${isWorkflows ? `/${s.name}` : s.name}](../${s.name}/SKILL.md) | ${clip(s.description)} |`),
    '',
  ];
  return `${lines.join('\n')}`;
}

function catalog(r, gs) {
  const real = r.skills.filter((s) => !s.index);
  const visible = real.filter((s) => s.visible);
  const wf = gs.find((g) => g.key === WORKFLOWS_KEY);
  const lines = [
    '# Catalog',
    '',
    MARKER,
    '',
    `**${real.length} skills** (${wf.items.length} slash-command workflows, ${real.length - wf.items.length} knowledge skills) · **${gs.length} index skills** · **${r.agents.length} subagents** · **${r.rules.length} rules**`,
    '',
    `Model-visible footprint: ~${r.stats.budgetTokens} tokens of Antigravity's 20,000-token customization budget.`,
    '',
    '## Always visible to the agent',
    '',
    'The index skills and a small core set. Everything else is slash-only and reached through an index.',
    '',
    '| Skill | What it does |',
    '| :--- | :--- |',
    ...gs.map((g) => `| \`${g.slug}\` | ${short(g.description.replace('{n}', String(g.items.length)))} |`),
    ...visible.map((s) => `| \`${s.name}\` | ${short(s.description)} |`),
    '',
    '## Workflows (slash commands)',
    '',
    '| Command | What it does |',
    '| :--- | :--- |',
    ...wf.items.map((s) => `| \`/${s.name}\` | ${short(s.description)} |`),
    '',
    '## Knowledge skills',
    '',
    'Run any of them as a slash command, or let the agent find them through the index named in each heading.',
    '',
  ];
  const grouped = new Set();
  for (const g of gs.filter((x) => x.key !== WORKFLOWS_KEY)) {
    if (!g.items.length) continue;
    g.items.forEach((s) => grouped.add(s.name));
    lines.push(`### ${g.key} (\`${g.slug}\`)`, '', '| Skill | What it covers |', '| :--- | :--- |', ...g.items.map((s) => `| \`${s.name}\` | ${short(s.description)} |`), '');
  }
  const other = real.filter((s) => !s.workflow && !grouped.has(s.name));
  if (other.length) lines.push('### Other', '', '| Skill | What it covers |', '| :--- | :--- |', ...other.map((s) => `| \`${s.name}\` | ${short(s.description)} |`), '');
  lines.push('## Subagents', '', '| Agent | Model | Tools | Role |', '| :--- | :--- | :--- | :--- |',
    ...r.agents.map((a) => `| \`${a.name}\` | ${a.model} | ${a.tools.some((t) => /write|replace/.test(t)) ? 'read + write' : a.tools.includes('run_command') ? 'read + run' : 'read-only'} | ${short(a.description)} |`), '');
  lines.push('## Rules', '', '| File | Trigger | Scope |', '| :--- | :--- | :--- |',
    ...r.rules.map((x) => `| \`${x.name}\` | ${x.trigger} | ${esc(x.globs || x.description || 'every turn')} |`), '');
  return `${lines.join('\n')}\n`;
}

/** @returns {{files: Record<string, string>, report: object}} repo-relative path → content */
function build() {
  const r = validateRepo(ROOT);
  const gs = groups(r);
  const files = {};
  for (const g of gs) files[path.join('skills', g.slug, 'SKILL.md')] = indexSkill(g);
  files[path.join('docs', 'CATALOG.md')] = catalog(r, gs);
  return { files, report: r };
}

if (require.main === module) {
  // Two passes: the index skills feed the budget numbers printed in the catalog.
  for (let pass = 0; pass < 2; pass++) {
    const { files } = build();
    for (const [rel, text] of Object.entries(files)) {
      fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
      fs.writeFileSync(path.join(ROOT, rel), text);
    }
  }
  const { report } = build();
  console.log(`Wrote ${Object.keys(CATEGORIES).length} index skills and docs/CATALOG.md: ${report.stats.skills} skills, ${report.stats.agents} agents, ${report.stats.rules} rules, ~${report.stats.budgetTokens} budget tokens`);
}

module.exports = { build };
