#!/usr/bin/env node
'use strict';
/** Generates docs/CATALOG.md from the skills, agents and rules on disk. Run: npm run catalog */
const fs = require('node:fs');
const path = require('node:path');
const { validateRepo } = require('./lib/validate');

const ROOT = path.resolve(__dirname, '..');
const GROUPS = [
  ['AI and agent engineering', ['gemini-api', 'google-adk', 'antigravity-customization', 'antigravity-sdk-orchestrator', 'mcp-server-development', 'prompt-engineering', 'agent-evals', 'rag-pipelines', 'llm-cost-routing', 'subagent-delegation', 'context-compaction']],
  ['Architecture and backend', ['software-architecture', 'api-design', 'backend-patterns', 'database-design', 'auth-patterns', 'python-fastapi', 'golang-services', 'rust-systems']],
  ['Frontend and mobile', ['frontend-react-nextjs', 'web-performance', 'accessibility-a11y', 'browser-automation', 'flutter-mobile']],
  ['Quality', ['tdd-testing', 'safe-refactor', 'documentation-writing', 'git-workflow']],
  ['Security', ['security-audit', 'agent-shield', 'credential-sanitizer', 'sandbox-isolation']],
  ['Cloud and DevOps', ['cloud-devops', 'docker-containers', 'kubernetes-gke', 'terraform-iac', 'ci-cd-github-actions', 'observability-otel']],
  ['Games', ['game-architecture', 'godot-engine', 'threejs-webgl', 'procedural-generation', 'game-audio-sfx']],
  ['Media', ['remotion-motion-graphics', 'ffmpeg-multimedia', 'ai-image-generation', 'image-processing-canvas', 'video-production-pipeline']],
  ['Business and growth', ['brand-discovery', 'growth-marketing', 'seo-audit', 'copywriting', 'pricing-strategy']],
];

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const short = (s) => esc(String(s).split(/(?<=\.)\s/)[0]);

function build() {
  const r = validateRepo(ROOT);
  const workflows = r.skills.filter((s) => s.workflow);
  const knowledge = r.skills.filter((s) => !s.workflow);
  const grouped = new Set(GROUPS.flatMap(([, names]) => names));
  const lines = [
    '# Catalog',
    '',
    '<!-- Generated by scripts/catalog.js. Do not edit by hand; run `npm run catalog`. -->',
    '',
    `**${r.skills.length} skills** (${workflows.length} slash-command workflows, ${knowledge.length} knowledge skills) · **${r.agents.length} subagents** · **${r.rules.length} rules**`,
    '',
    '## Workflows (slash commands)',
    '',
    '| Command | What it does |',
    '| :--- | :--- |',
    ...workflows.map((s) => `| \`/${s.name}\` | ${short(s.description)} |`),
    '',
    '## Knowledge skills',
    '',
    'Loaded on demand when the task matches the description.',
    '',
  ];
  for (const [title, names] of GROUPS) {
    const items = knowledge.filter((s) => names.includes(s.name));
    if (!items.length) continue;
    lines.push(`### ${title}`, '', '| Skill | What it covers |', '| :--- | :--- |', ...items.map((s) => `| \`${s.name}\` | ${short(s.description)} |`), '');
  }
  const other = knowledge.filter((s) => !grouped.has(s.name));
  if (other.length) lines.push('### Other', '', '| Skill | What it covers |', '| :--- | :--- |', ...other.map((s) => `| \`${s.name}\` | ${short(s.description)} |`), '');
  lines.push('## Subagents', '', '| Agent | Model | Tools | Role |', '| :--- | :--- | :--- | :--- |',
    ...r.agents.map((a) => `| \`${a.name}\` | ${a.model} | ${a.tools.some((t) => /write|replace/.test(t)) ? 'read + write' : a.tools.includes('run_command') ? 'read + run' : 'read-only'} | ${short(a.description)} |`), '');
  lines.push('## Rules', '', '| File | Trigger | Scope |', '| :--- | :--- | :--- |',
    ...r.rules.map((x) => `| \`${x.name}\` | ${x.trigger} | ${esc(x.globs || x.description || 'every turn')} |`), '');
  return { text: `${lines.join('\n')}\n`, report: r };
}

if (require.main === module) {
  const { text, report } = build();
  const out = path.join(ROOT, 'docs', 'CATALOG.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, text);
  console.log(`Wrote ${out}: ${report.stats.skills} skills, ${report.stats.agents} agents, ${report.stats.rules} rules`);
}

module.exports = { build };
